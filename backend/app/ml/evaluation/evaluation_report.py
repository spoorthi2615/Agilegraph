from pydantic import BaseModel, Field
from typing import Dict, Any, Optional
from datetime import datetime, timezone

class EvaluationReport(BaseModel):
    """
    Standardized schema for all evaluation reports generated by the GATv2 Evaluator.
    Serves as the data transfer object for JSON, CSV, and Markdown serialization.
    """
    model_version: str = Field(default="gatv2_best.pt")
    dataset_version: str = Field(default="latest")
    evaluation_time: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    
    # Global metrics
    overall_accuracy: float = 0.0
    
    macro_precision: float = 0.0
    macro_recall: float = 0.0
    macro_f1: float = 0.0
    
    weighted_precision: float = 0.0
    weighted_recall: float = 0.0
    weighted_f1: float = 0.0
    
    roc_auc: Optional[float] = None
    
    # Per-class metrics: class_id -> {"precision": float, "recall": float, "f1": float, "support": int}
    per_class_metrics: Dict[str, Dict[str, float]] = Field(default_factory=dict)
    
    # Confusion matrix layout
    # {"classes": [0, 1, 2, 3], "matrix": [[...], ...], "stats": {...}}
    confusion_matrix: Dict[str, Any] = Field(default_factory=dict)

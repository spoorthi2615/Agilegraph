from datetime import datetime, timezone
from typing import Any, Dict, List
from uuid import UUID, uuid4

from pydantic import BaseModel, Field


class NodePrediction(BaseModel):
    """
    Sub-model representing an AI prediction explicitly mapped back to a specific node UUID.
    """

    node_id: str
    risk_score: float
    label: int


class InferenceResult(BaseModel):
    """
    Domain model representing the AI predictions generated by a trained GATv2 model,
    fully traceable and mapped back to the original source code graph nodes.
    """

    inference_id: UUID = Field(default_factory=uuid4)
    model_id: UUID
    dataset_id: UUID

    inferred_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    total_predictions: int

    # Traceable predictions seamlessly mapped to their originating nodes
    node_predictions: List[NodePrediction]

    classification_threshold: float
    inference_duration_seconds: float
    inference_completed: bool

    metadata: Dict[str, Any] = Field(default_factory=dict)
